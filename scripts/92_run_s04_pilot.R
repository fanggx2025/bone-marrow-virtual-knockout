## 92_run_s04_pilot.R —— S04 试点：只敲对照组 7 个基因
## =============================================================================
## 【为什么先跑试点】
##   S04 有两个"一次性"成本：建 WT 网络（10 张 PC-net）和逐基因敲除。
##   全量候选 194 个基因之前，必须先用已知方向的对照基因确认：
##     ① 流程不崩（并行、补零、张量分解都对）
##     ② **方向判读没搞反** —— RUNX2 必须判为"促进成骨/成骨所需"，
##        PPARG 必须判为"抑制成骨"。跑反了整篇文章结论就废了。
##     ③ 量出单基因敲除耗时，才能推算 194 个要多久
## =============================================================================

source("scripts/99_start.R")
source("R/04_virtual_knockout.R")

CTRL <- c("RUNX2",  # 成骨主控 TF   → 预期【促进成骨】(=成骨所需，不可药靶)
          "SP7",    # Osterix       → 预期【促进成骨】
          "PPARG",  # 成脂主控      → 预期【抑制成骨】★
          "CEBPB",  # 成脂          → 预期【抑制成骨】★
          "CXCL12", # 静息 BMSC     → 预期【抑制成骨】★（敲掉把细胞推出静息）
          "LPL",    # 起点+成脂     → 预期【抑制成骨】★
          "KITLG")  # 起点标记      → 预期【抑制成骨】★

res <- run_s04(ko_genes = CTRL, hvg_n = 1000L,
               n_net = 10L, n_workers_ko = 7L,
               rebuild = TRUE)

cat("\n\n════════════════════════════════════════════\n")
cat("试点判读核对（预期 vs 实际）\n")
cat("════════════════════════════════════════════\n")
exp_map <- c(RUNX2 = "促进成骨", SP7 = "促进成骨", PPARG = "抑制成骨",
             CEBPB = "抑制成骨", CXCL12 = "抑制成骨", LPL = "抑制成骨",
             KITLG = "抑制成骨")
chk <- res$scores[, c("KO", "direction", "med_w_end", "p_repress", "p_activate",
                      "n_end_sig", "verdict")]
chk$预期 <- exp_map[chk$KO]
chk$符合 <- ifelse(chk$direction == chk$预期, "✓",
              ifelse(chk$direction == "无显著方向", "—(无方向)", "✗ 反了"))
print(chk, row.names = FALSE)
